func (m *SambaManager) runSambaTool(ctx context.Context, name string, args []string, stdin string) (string, error) {
	cmd := exec.CommandContext(ctx, m.binary(name), args...)
	cmd.Env = m.env()
	cmd.Dir = m.dataDir
	if stdin != "" {
		cmd.Stdin = strings.NewReader(stdin)
	}
	var out bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &out
	err := cmd.Run()
	text := strings.TrimSpace(out.String())
	if err != nil {
		return text, fmt.Errorf("%s: %w: %s", name, err, redactSecrets(text))
	}
	return text, nil
}

func (m *SambaManager) userArgs(extra ...string) []string {
	return append([]string{"-c", m.confPath}, extra...)
}

func (m *SambaManager) AddUser(name, password string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	// smbpasswd -s reads the new password twice from stdin. It never appears
	// in argv, the environment, or the log.
	_, err := m.runSambaTool(ctx, "smbpasswd",
		m.userArgs("-s", "-a", name), password+"\n"+password+"\n")
	if err != nil {
		return err
	}
	m.log.Infof("smb", "user %s added to passdb", name)
	return nil
}

func (m *SambaManager) SetUserPassword(name, password string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	_, err := m.runSambaTool(ctx, "smbpasswd",
		m.userArgs("-s", name), password+"\n"+password+"\n")
	if err != nil {
		return err
	}
	m.log.Infof("smb", "password changed for user %s", name)
	return nil
}

func (m *SambaManager) DeleteUser(name string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	_, err := m.runSambaTool(ctx, "smbpasswd", m.userArgs("-x", name), "")
	if err != nil {
		// Deleting a user that never made it into passdb is not fatal.
		if strings.Contains(strings.ToLower(err.Error()), "not found") ||
			strings.Contains(strings.ToLower(err.Error()), "no such user") {
			return nil
		}
		return err
	}
	m.log.Infof("smb", "user %s removed from passdb", name)
	return nil
}

func (m *SambaManager) SetUserEnabled(name string, enabled bool) error {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	flag := "-e"
	if !enabled {
		flag = "-d"
	}
	_, err := m.runSambaTool(ctx, "smbpasswd", m.userArgs(flag, name), "")
	if err != nil {
		return err
	}
	m.log.Infof("smb", "user %s enabled=%v", name, enabled)
	return nil
}

func (m *SambaManager) CheckConfig() (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	return m.runSambaTool(ctx, "testparm", []string{"-s", "-c", m.confPath}, "")
}

// smbdProcessCount reads /proc to count live smbd processes. It is used for
// diagnostics only; the supervisor relies on the direct child wait result.
func smbdProcessCount() int {
	entries, err := os.ReadDir("/proc")
	if err != nil {
		return 0
	}
	n := 0
	for _, e := range entries {
		if !e.IsDir() || e.Name() == "" || e.Name()[0] < '0' || e.Name()[0] > '9' {
			continue
		}
		pid, _ := strconv.Atoi(e.Name())
		comm, err := os.ReadFile(fmt.Sprintf("/proc/%d/comm", pid))
		if err == nil && strings.TrimSpace(string(comm)) == "smbd" {
			n++
		}
	}
	return n
}

