// SambaManager owns the smbd process and the generated smb.conf. It never
// edits smb.conf by hand: the file is always rendered from Config so the API
// and the Samba view cannot drift apart.
type SambaManager struct {
	cfg     *Config
	binDir  string
	libDir  string
	dataDir string
	logDir  string
	runDir  string
	log     *Logger

	cmd       *exec.Cmd
	pid       int
	startedAt time.Time
	console   *RotatingWriter
	confPath  string
	waitDone  chan struct{}
	waitErr   error
}

func NewSambaManager(cfg *Config, moduleDir, dataDir string, log *Logger) *SambaManager {
	return &SambaManager{
		cfg:      cfg,
		binDir:   filepath.Join(moduleDir, "bin"),
		libDir:   filepath.Join(moduleDir, "lib"),
		dataDir:  dataDir,
		logDir:   filepath.Join(dataDir, "logs"),
		runDir:   filepath.Join(dataDir, "run"),
		log:      log,
		confPath: filepath.Join(dataDir, "samba", "smb.conf"),
	}
}

func (m *SambaManager) sambaDir(sub string) string {
	return filepath.Join(m.dataDir, "samba", sub)
}

func (m *SambaManager) ensureDirs() error {
	dirs := []string{
		m.sambaDir("private"), m.sambaDir("lock"), m.sambaDir("state"),
		m.sambaDir("cache"), m.sambaDir("pid"), m.sambaDir("ncalrpc"),
		m.runDir, m.logDir, filepath.Join(m.dataDir, "tmp"),
		filepath.Join(m.dataDir, "var", "log", "samba"),
		filepath.Join(filepath.Dir(m.binDir), "var", "log", "samba"),
	}
	for _, d := range dirs {
		if err := os.MkdirAll(d, 0o700); err != nil {
			return err
		}
		_ = os.Chmod(d, 0o700)
	}
	return nil
}

func (m *SambaManager) env() []string {
	return []string{
		"PATH=" + m.binDir + ":/system/bin:/system/xbin",
		"LD_LIBRARY_PATH=" + m.libDir + ":" + filepath.Join(m.libDir, "samba"),
		"TMPDIR=" + filepath.Join(m.dataDir, "tmp"),
		"HOME=" + m.dataDir,
		"ANDROID_DATA=/data",
		"ANDROID_ROOT=/system",
		"LANG=C.UTF-8",
	}
}

func (m *SambaManager) binary(name string) string {
	return filepath.Join(m.binDir, name)
}

// RenderConfig builds the Samba configuration from validated Config plus the
// currently selected interface. Paths are mapped for root/FUSE compatibility.
func RenderConfig(cfg *Config, iface, dataDir string) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	w("# Generated by asrd from config.json. Do not edit by hand;")
	w("# changes are overwritten on the next apply.")
	w("[global]")
	w("   server role = standalone server")
	w("   server string = Android SMB Relay")
	w("   netbios name = %s", cfg.SMB.NetBIOSName)
	w("   workgroup = %s", cfg.SMB.Workgroup)
	w("   security = user")
	w("   passdb backend = tdbsam")
	w("   obey pam restrictions = no")
	w("   pam password change = no")
	w("   unix password sync = no")
	w("   ntlm auth = ntlmv2-only")
	w("   restrict anonymous = %d", boolInt(cfg.SMB.AllowAnonymous == false, 2, 0))
	w("   map to guest = %s", boolString(cfg.SMB.GuestAccess || cfg.SMB.AllowAnonymous, "Bad User", "Never"))
	w("   guest account = nobody")

	w("   server min protocol = %s", cfg.SMB.MinProtocol)
	w("   server max protocol = %s", cfg.SMB.MaxProtocol)
	signing := cfg.SMB.Signing
	if signing == "off" {
		signing = "disabled"
	}
	w("   server signing = %s", signing)
	w("   server smb encrypt = %s", cfg.SMB.Encryption)
	w("   server multi channel support = no")
	w("   smb ports = %d", cfg.SMB.Port)
	if iface != "" && iface != "auto" {
		w("   interfaces = %s", iface)
		w("   bind interfaces only = yes")
	}

	w("   private dir = %s", filepath.Join(dataDir, "samba", "private"))
	w("   lock directory = %s", filepath.Join(dataDir, "samba", "lock"))
	w("   state directory = %s", filepath.Join(dataDir, "samba", "state"))
	w("   cache directory = %s", filepath.Join(dataDir, "samba", "cache"))
	w("   pid directory = %s", filepath.Join(dataDir, "samba", "pid"))
	w("   ncalrpc dir = %s", filepath.Join(dataDir, "samba", "ncalrpc"))
	w("   log file = %s", filepath.Join(dataDir, "logs", "smbd.log"))
	w("   max log size = %d", cfg.Log.MaxSizeKB)
	w("   log level = %d", sambaLogLevel(cfg.Log.Level))
	w("   debug timestamp = yes")
	w("   debug pid = yes")

	w("   load printers = no")
	w("   printing = bsd")
	w("   printcap name = /dev/null")
	w("   disable spoolss = yes")
	w("   show add printer wizard = no")
	w("   dns proxy = no")
	w("   name resolve order = host")
	w("   hostname lookups = no")
	w("   unix extensions = no")
	w("   wide links = no")
	w("   follow symlinks = no")
	w("   kernel oplocks = no")
	w("   use sendfile = no")
	w("   use mmap = no")
	w("   aio read size = 0")
	w("   aio write size = 0")
	w("   smb2 max read = 1048576")
	w("   smb2 max write = 1048576")
	w("   nt acl support = no")
	w("   store dos attributes = no")
	w("   map archive = no")
	w("   map hidden = no")
	w("   map system = no")
	w("   ea support = no")
	w("   create mask = 0666")
	w("   directory mask = 0777")
	w("   force create mode = 0000")
	w("   force directory mode = 0000")
	w("   dos filemode = no")
	w("   hide dot files = no")
	w("   delete readonly = no")
	w("   deadtime = 15")
	w("   keepalive = 300")
	w("   max smbd processes = 64")
	w("")

	users := enabledUsers(cfg)
	for i := range cfg.Shares {
		s := &cfg.Shares[i]
		if !s.Enabled {
			continue
		}
		w("[%s]", s.Name)
		w("   path = %s", RuntimePath(cfg, s.Path))
		w("   comment = %s", s.Comment)
		w("   browseable = %s", boolString(!s.Hidden, "yes", "no"))
		w("   read only = %s", boolString(s.ReadOnly, "yes", "no"))
		if s.GuestOK {
			w("   guest ok = yes")
		} else {
			w("   guest ok = no")
			if len(users) > 0 {
				w("   valid users = %s", strings.Join(users, ", "))
			} else {
				// No users and no guest access: the share is intentionally
				// unreachable rather than open to everyone.
				w("   valid users = nobody")
			}
		}
		w("   force user = %s", cfg.SMB.ForceUser)
		if cfg.SMB.ForceUser == "root" {
			w("   force group = root")
		}
		w("   inherit permissions = no")
		w("   writeable = %s", boolString(!s.ReadOnly, "yes", "no"))
		w("")
	}
	return b.String()
}

func sambaLogLevel(level string) int {
	switch level {
	case "debug":
		return 4
	case "info":
		return 1
	case "warn":
		return 0
	case "error":
		return 0
	}
	return 1
}

func boolString(v bool, a, b string) string {
	if v {
		return a
	}
	return b
}

func boolInt(v bool, a, b int) int {
	if v {
		return a
	}
	return b
}

func enabledUsers(cfg *Config) []string {
	var out []string
	for _, u := range cfg.Users {
		if u.Enabled {
			out = append(out, u.Name)
		}
	}
	return out
}

func (m *SambaManager) WriteConfig(iface string) error {
	if err := m.ensureDirs(); err != nil {
		return err
	}
	body := RenderConfig(m.cfg, iface, m.dataDir)
	return atomicWriteFile(m.confPath, []byte(body), 0o600)
}

func (m *SambaManager) ConfPath() string { return m.confPath }

// Samba's foreground mode (-F) exits on Android when the first connection is
// accepted (get_remote_hostname sees an address bionic rejects), while the
// daemon mode (-D) forks a worker that handles connections correctly. We
// therefore run smbd in daemon mode and supervise it through its pidfile.
func (m *SambaManager) Start(iface string) error {
	if m.PID() != 0 {
		return errors.New("smbd already started")
	}
	if _, err := os.Stat(m.binary("smbd")); err != nil {
		return fmt.Errorf("smbd binary missing: %w", err)
	}
	if err := m.WriteConfig(iface); err != nil {
		return err
	}
	_ = os.Remove(filepath.Join(m.sambaDir("pid"), "smbd.pid"))
	consolePath := filepath.Join(m.logDir, "smbd-console.log")
	w, err := NewRotatingWriter(consolePath, m.cfg.Log.MaxSizeKB, m.cfg.Log.MaxFiles)
	if err != nil {
		return err
	}
	m.console = w
	cmd := exec.Command(m.binary("smbd"), "-D", "-s", m.confPath, "-l", m.logDir)
	cmd.Env = m.env()
	cmd.Dir = m.dataDir
	cmd.Stdout = w
	cmd.Stderr = w
	setProcessGroup(cmd)
	startErr := cmd.Run()
	if startErr != nil {
		_ = w.Close()
		m.console = nil
		return fmt.Errorf("start smbd: %w", startErr)
	}
	pid := 0
	for i := 0; i < 30; i++ {
		if p := m.readPidFile(); p > 0 && processAlive(p) {
			pid = p
			break
		}
		time.Sleep(100 * time.Millisecond)
	}
	if pid == 0 {
		pid = findSambaMaster(m.confPath)
	}
	if pid == 0 {
		_ = w.Close()
		m.console = nil
		return errors.New("smbd daemon did not stay running; see smbd.log/smbd-console.log")
	}
	m.pid = pid
	m.startedAt = time.Now()
	done := make(chan struct{})
	m.waitDone = done
	m.waitErr = nil
	go m.monitor(pid, done)
	m.log.Infof("smb", "smbd started pid=%d iface=%s port=%d conf=%s", pid, iface, m.cfg.SMB.Port, m.confPath)
	return nil
}

func (m *SambaManager) monitor(pid int, done chan struct{}) {
	ticker := time.NewTicker(time.Second)
	defer ticker.Stop()
	for range ticker.C {
		if !processAlive(pid) {
			m.waitErr = fmt.Errorf("smbd pid %d exited", pid)
			close(done)
			return
		}
	}
}

func (m *SambaManager) Wait() error {
	if m.waitDone == nil {
		return nil
	}
	<-m.waitDone
	return m.waitErr
}

func (m *SambaManager) PID() int {
	if m.pid > 0 && processAlive(m.pid) {
		return m.pid
	}
	return 0
}

func (m *SambaManager) StartedAt() time.Time { return m.startedAt }

func (m *SambaManager) Stop(grace time.Duration) error {
	pid := m.pid
	if pid == 0 {
		return nil
	}
	children := childPIDs(pid)
	m.log.Infof("smb", "stopping smbd pid=%d children=%v", pid, children)
	_ = sendSignal(pid, syscall.SIGTERM)
	if m.waitDone != nil {
		select {
		case <-m.waitDone:
		case <-time.After(grace):
			_ = sendSignal(pid, syscall.SIGKILL)
			select {
			case <-m.waitDone:
			case <-time.After(2 * time.Second):
			}
		}
	}
	for _, c := range children {
		if processAlive(c) {
			_ = sendSignal(c, syscall.SIGKILL)
		}
	}
	if m.console != nil {
		_ = m.console.Close()
		m.console = nil
	}
	m.pid = 0
	m.waitDone = nil
	m.startedAt = time.Time{}
	_ = os.Remove(filepath.Join(m.sambaDir("pid"), "smbd.pid"))
	return nil
}

// Reload asks the smbd master to re-read smb.conf. New shares normally become
// visible without dropping established sessions.
func (m *SambaManager) Reload() error {
	if m.PID() == 0 {
		return errors.New("smbd is not running")
	}
	if err := sendSignal(m.pid, syscall.SIGHUP); err != nil {
		return fmt.Errorf("SIGHUP smbd: %w", err)
	}
	return nil
}

func (m *SambaManager) readPidFile() int {
	data, err := os.ReadFile(filepath.Join(m.sambaDir("pid"), "smbd.pid"))
	if err != nil {
		return 0
	}
	pid, _ := strconv.Atoi(strings.TrimSpace(string(data)))
	return pid
}

func findSambaMaster(confPath string) int {
	entries, err := os.ReadDir("/proc")
	if err != nil {
		return 0
	}
	for _, e := range entries {
		if !e.IsDir() || e.Name() == "" || e.Name()[0] < '0' || e.Name()[0] > '9' {
			continue
		}
		data, err := os.ReadFile(filepath.Join("/proc", e.Name(), "cmdline"))
		if err != nil {
			continue
		}
		cmdline := strings.ReplaceAll(strings.TrimRight(string(data), "\x00"), "\x00", " ")
		if !strings.Contains(cmdline, "smbd") || !strings.Contains(cmdline, confPath) {
			continue
		}
		pid, _ := strconv.Atoi(e.Name())
		if pid > 0 {
			return pid
		}
	}
	return 0
}

func childPIDs(pid int) []int {
	var out []int
	entries, err := os.ReadDir("/proc")
	if err != nil {
		return out
	}
	for _, e := range entries {
		if !e.IsDir() || e.Name() == "" || e.Name()[0] < '0' || e.Name()[0] > '9' {
			continue
		}
		data, err := os.ReadFile(filepath.Join("/proc", e.Name(), "stat"))
		if err != nil {
			continue
		}
		s := string(data)
		i := strings.LastIndex(s, ")")
		if i < 0 {
			continue
		}
		fields := strings.Fields(s[i+1:])
		if len(fields) < 2 {
			continue
		}
		ppid, _ := strconv.Atoi(fields[1])
		if ppid == pid {
			child, _ := strconv.Atoi(e.Name())
			if child > 0 {
				out = append(out, child)
			}
		}
	}
	return out
}

